use crate::models::{
    build_google_scholar_cited_by_url, build_google_scholar_url, compute_creativity_ratio,
    PaperNode,
};

pub fn make_curated_node(
    id: &str,
    title: &str,
    authors: Vec<&str>,
    year: u32,
    venue: &str,
    doi_url: Option<&str>,
    pdf_url: Option<&str>,
    openalex_id: Option<&str>,
    abstract_snippet: &str,
    signed_level: i32,
    bfs_level: u32,
    global_references_count: usize,
    global_citations_count: usize,
) -> PaperNode {
    let authors_str: Vec<String> = authors.into_iter().map(|s| s.to_string()).collect();
    let gs_url = build_google_scholar_url(title, &authors_str);
    let gs_cited_url = build_google_scholar_cited_by_url(title);
    let global_creativity_score =
        compute_creativity_ratio(global_citations_count, global_references_count);

    let mut node = PaperNode {
        id: id.to_string(),
        title: title.to_string(),
        authors: authors_str,
        year: Some(year),
        venue: Some(venue.to_string()),
        doi_url: doi_url.map(|s| s.to_string()),
        pdf_url: pdf_url.map(|s| s.to_string()),
        google_scholar_url: gs_url,
        google_scholar_cited_by_url: gs_cited_url,
        openalex_id: openalex_id.map(|s| s.to_string()),
        abstract_snippet: Some(abstract_snippet.to_string()),
        signed_level,
        bfs_level,
        in_degree: 0,
        out_degree: 0,
        global_references_count,
        global_citations_count,
        creativity_score: global_creativity_score,
        smoothed_creativity_score: 1.0,
        global_creativity_score: 0.0,
        expanded: false,
    };
    node.recompute_creativity();
    node
}

